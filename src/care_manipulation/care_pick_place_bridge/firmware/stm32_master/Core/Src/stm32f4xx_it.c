extern UART_HandleTypeDef huart2;
extern UART_HandleTypeDef huart3;
extern TIM_HandleTypeDef htim3;
extern DMA_HandleTypeDef  hdma_usart3_rx;

/* TIM3 is also the bounded coordinated-step scheduler. Clear the update flag
 * here and keep the hot path small enough for the 8 kHz worst case. */
void TIM3_IRQHandler(void)
{
    if (__HAL_TIM_GET_FLAG(&htim3, TIM_FLAG_UPDATE) != RESET &&
        __HAL_TIM_GET_IT_SOURCE(&htim3, TIM_IT_UPDATE) != RESET) {
        __HAL_TIM_CLEAR_IT(&htim3, TIM_IT_UPDATE);
        motor_coordinated_tim3_irq();
    }
}

/* USART2 global interrupt -- drives the single-byte interrupt-RX path used
 * by the motor test command parser in main.c. HAL_UART_IRQHandler invokes
 * HAL_UART_RxCpltCallback() once the requested byte arrives. NVIC for this
 * line is enabled manually in main() (not via CubeMX IOC) so it survives
 * regeneration; if you later add USART2 NVIC to the IOC you can delete the
 * manual HAL_NVIC_EnableIRQ(USART2_IRQn) call. */
void USART2_IRQHandler(void)
{
    HAL_UART_IRQHandler(&huart2);
}

/* DMA1 Stream 1 interrupt -- HAL housekeeping (transfer-complete/half/error)
 * for the USART3 RX circular DMA. The data itself is drained from the circular
 * buffer by the ESP32 sensor-node parser in main(). */
void DMA1_Stream1_IRQHandler(void)
{
    HAL_DMA_IRQHandler(&hdma_usart3_rx);
}

/* USART3 global interrupt -- routes USART3 errors (overrun/framing/noise) into
 * HAL, which invokes HAL_UART_ErrorCallback() in main.c to re-arm the DMA. */
void USART3_IRQHandler(void)
{
    HAL_UART_IRQHandler(&huart3);
}

